const get = db.prepare('SELECT rowid, domain, country, products, description, notes FROM customer_pool WHERE rowid = ?');
const update = db.prepare(`
  UPDATE customer_pool
  SET products = @products,
      description = @description,
      country = @country,
      notes = @notes
  WHERE rowid = @rowid
`);

let changed = 0;
const run = db.transaction(() => {
  for (const [rowid, productsZh, descriptionZh] of fixes) {
    const row = get.get(rowid);
    if (!row) continue;
    const country = /\.br$/i.test(row.domain) || /\.com\.br$/i.test(row.domain) || /\.ind\.br$/i.test(row.domain)
      ? '巴西'
      : row.country;
    const note = `[translation ${new Date().toISOString()}] rowid>=879 products/description converted to Chinese with original preserved.`;
    update.run({
      rowid,
      products: withOriginal(productsZh, row.products),
      description: withOriginal(descriptionZh, row.description),
      country,
      notes: row.notes && !row.notes.includes('[translation ')
        ? `${row.notes}\n${note}`
        : (row.notes || note),
    });
    changed += 1;
  }
});

run();
